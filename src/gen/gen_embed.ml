(* Generates src/lib/embedded.ml: the files of src/std/ and of src/tools/, embedded in the binary. The tools' other files,
   site.css and site.js, keep their extension.

   Each file is a string that only code names, through a match on its name: no block of the binary's data points to it,
   so the loader of the system has nothing to rewrite there at each start (a list of pairs put a pointer next to every
   file, and the start wrote some 40 pages of it), and a file is read only when it is used. A name not there gives "",
   which no file is. *)

let () =
  let paths = List.tl (Array.to_list Sys.argv) in
  let in_tools path = Filename.basename (Filename.dirname path) = "tools" in
  let is_code path = Filename.check_suffix path ".ce" in
  let read path =
    let s = In_channel.with_open_bin path In_channel.input_all in
    if s = "" then (prerr_endline ("gen_embed: " ^ path ^ " is empty"); exit 2);
    s
  in
  let table ?(name = fun path -> Filename.remove_extension (Filename.basename path)) ?(listed = true) title paths =
    if listed then
      Printf.printf "let %s_names = [ %s ]\n" title (String.concat "; " (List.map (fun p -> Printf.sprintf "%S" (name p)) paths));
    Printf.printf "let %s_source = function\n" title;
    List.iter (fun path -> Printf.printf "  | %S -> %S\n" (name path) (read path)) paths;
    print_string "  | _ -> \"\"\n"
  in
  print_string "(* Generated by src/gen/gen_embed.ml. Do not edit by hand. *)\n";
  table "file" (List.filter (fun p -> not (in_tools p)) paths);
  table "tool" (List.filter (fun p -> in_tools p && is_code p) paths);
  table ~name:Filename.basename ~listed:false "asset" (List.filter (fun p -> in_tools p && not (is_code p)) paths);
  print_string
    "let some = function \"\" -> None | s -> Some s\n\
     let names = file_names\n\
     let file name = some (file_source name)\n\
     let tools = tool_names\n\
     let tool name = some (tool_source name)\n\
     let asset name = some (asset_source name)\n\
     let holds src = List.exists (fun name -> file_source name == src) file_names\n"

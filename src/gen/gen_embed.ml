(* Generates src/lib/embedded.ml: the files of src/std/ and of src/tools/, embedded in the binary. *)

let () =
  let paths = List.tl (Array.to_list Sys.argv) in
  let in_tools path = Filename.basename (Filename.dirname path) = "tools" in
  let list title paths =
    Printf.printf "let %s = [\n" title;
    List.iter
      (fun path ->
         let name = Filename.remove_extension (Filename.basename path) in
         Printf.printf "  (%S, %S);\n" name (In_channel.with_open_bin path In_channel.input_all))
      paths;
    print_string "]\n"
  in
  print_string "(* Generated by src/gen/gen_embed.ml. Do not edit by hand. *)\n";
  list "files" (List.filter (fun p -> not (in_tools p)) paths);
  list "tools" (List.filter in_tools paths)

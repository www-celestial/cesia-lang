(* Generates src/lib/embedded.ml: the files of src/std/ and of src/tools/, embedded in the binary. The tools' other files,
   site.css and site.js, keep their extension. *)

let () =
  let paths = List.tl (Array.to_list Sys.argv) in
  let in_tools path = Filename.basename (Filename.dirname path) = "tools" in
  let is_code path = Filename.check_suffix path ".ce" in
  let list ?(name = fun path -> Filename.remove_extension (Filename.basename path)) title paths =
    Printf.printf "let %s = [\n" title;
    List.iter
      (fun path ->
         Printf.printf "  (%S, %S);\n" (name path) (In_channel.with_open_bin path In_channel.input_all))
      paths;
    print_string "]\n"
  in
  print_string "(* Generated by src/gen/gen_embed.ml. Do not edit by hand. *)\n";
  list "files" (List.filter (fun p -> not (in_tools p)) paths);
  list "tools" (List.filter (fun p -> in_tools p && is_code p) paths);
  list ~name:Filename.basename "assets" (List.filter (fun p -> in_tools p && not (is_code p)) paths)

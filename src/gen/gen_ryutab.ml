(* Generates src/lib/ryutab.ml, the tables of src/lib/ryu.ml, as strings, which the binary holds as static data, built at
   no start-up. First those of Ryu (Adams, PLDI 2018), its d2s_full_table.h, which ryu.ml multiplies a mantissa by: each
   entry a number of at most 126 bits, as five limbs of 30 bits, low first, each in 4 bytes, little-endian, 20 bytes an
   entry.
   - pow5, i = 0..341: the 125 high bits of 5^i, truncated (5^i itself, shifted left, while it has fewer bits). Ryu
     stops at 325; 326..341 serve the subnormals, whose mantissa ryu.ml first shifts left by up to 52 bits.
   - inv, q = 0..290: floor(2^k / 5^q) + 1, k = bits(5^q) - 1 + 125.
   Exact integers in limbs of 30 bits, low first: 5^i by products by 5, floor(2^b / 5^q) by divisions by 5 of 2^b, since
   floor(floor(a / 5) / 5) = floor(a / 25).
   Then quads: the four digits of each of 0..9999, "0000" to "9999", which ryu.ml writes four at a time. *)

let limb_bits = 30
let base = 1 lsl limb_bits
let size = 40 (* 1200 bits: 5^341 has 793, 2^810 811 *)

let bits a =
  let rec top k = if k < 0 then 0 else if a.(k) <> 0 then k else top (k - 1) in
  let k = top (size - 1) in
  let rec width v = if v = 0 then 0 else 1 + width (v lsr 1) in
  (k * limb_bits) + width a.(k)

let times5 a =
  let carry = ref 0 in
  for k = 0 to size - 1 do
    let v = (a.(k) * 5) + !carry in
    a.(k) <- v land (base - 1);
    carry := v lsr limb_bits
  done;
  assert (!carry = 0)

let div5 a =
  let rest = ref 0 in
  for k = size - 1 downto 0 do
    let v = (!rest * base) + a.(k) in
    a.(k) <- v / 5;
    rest := v mod 5
  done

(* a times 2^s, s < 0 shifting right (the bits shifted out are lost). *)
let shift a s =
  let r = Array.make size 0 in
  for b = 0 to (size * limb_bits) - 1 do
    let from = b - s in
    if from >= 0 && from < size * limb_bits && (a.(from / limb_bits) lsr (from mod limb_bits)) land 1 = 1 then
      r.(b / limb_bits) <- r.(b / limb_bits) lor (1 lsl (b mod limb_bits))
  done;
  r

let plus1 a =
  let rec go k = if a.(k) = base - 1 then (a.(k) <- 0; go (k + 1)) else a.(k) <- a.(k) + 1 in
  go 0

let entry buf t =
  if bits t > 126 then failwith "an entry of more than 126 bits";
  for k = 0 to 4 do
    for byte = 0 to 3 do
      Buffer.add_string buf (Printf.sprintf "\\%03d" ((t.(k) lsr (8 * byte)) land 0xFF))
    done
  done;
  Buffer.add_string buf "\\\n  "

let () =
  let pow5 = Buffer.create 40000 and inv = Buffer.create 40000 in
  let p = Array.make size 0 in
  p.(0) <- 1;
  for i = 0 to 341 do
    entry pow5 (shift p (125 - bits p));
    times5 p
  done;
  let big = 810 in
  let n = shift (let a = Array.make size 0 in a.(0) <- 1; a) big in
  let p = Array.make size 0 in
  p.(0) <- 1;
  for q = 0 to 290 do
    let k = bits p - 1 + 125 in
    let t = shift n (k - big) in
    plus1 t;
    entry inv t;
    div5 n;
    times5 p
  done;
  let quads = Buffer.create 50000 in
  for v = 0 to 9999 do
    Buffer.add_string quads (Printf.sprintf "%04d" v);
    if v mod 25 = 24 then Buffer.add_string quads "\\\n  "
  done;
  print_string "(* Generated by src/gen/gen_ryutab.ml. Do not edit by hand. *)\n\n";
  Printf.printf "let pow5 =\n  \"%s\"\n\n" (Buffer.contents pow5);
  Printf.printf "let inv =\n  \"%s\"\n\n" (Buffer.contents inv);
  Printf.printf "let quads =\n  \"%s\"\n" (Buffer.contents quads)

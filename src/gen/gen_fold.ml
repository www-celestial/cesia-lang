(* Writes src/lib/casefold.ml from CaseFolding.txt of the Unicode Character Database, its simple case folding: the
   statuses C and S, each a character to one character. Run by hand when Unicode gives a new version:

     curl -O https://www.unicode.org/Public/X.Y.Z/ucd/CaseFolding.txt
     dune build src/gen/gen_fold.exe && _build/default/src/gen/gen_fold.exe CaseFolding.txt > src/lib/casefold.ml

   then give the new version where text.Fold's entry in src/std/natives.ce names it, and in the CHANGELOG.

   The pairs become runs: characters one or two apart that move by the same distance, as A to Z, or the capitals and
   small letters of Latin Extended-A that alternate: four numbers each, its first character, its last, the step between
   two of them and the distance each moves, rising, for a binary search. *)

let () =
  let path = Sys.argv.(1) in
  let lines = In_channel.with_open_bin path In_channel.input_lines in
  let version =
    match lines with
    | first :: _ when String.starts_with ~prefix:"# CaseFolding-" first && String.ends_with ~suffix:".txt" first ->
      String.sub first 14 (String.length first - 18)
    | _ -> failwith (path ^ " doesn't start as CaseFolding.txt does")
  in
  let pair line =
    match String.split_on_char ';' line with
    | code :: status :: mapping :: _ when List.mem (String.trim status) [ "C"; "S" ] ->
      let hex s = int_of_string ("0x" ^ String.trim s) in
      Some (hex code, hex mapping)
    | _ -> None
  in
  let pairs = List.sort compare (List.filter_map (fun l -> if l = "" || l.[0] = '#' then None else pair l) lines) in
  (* What text.Fold takes for granted, in src/lib/lists.ml: A to Z are the only characters of ASCII that fold, by
     Char.lowercase_ascii; none folds to one more than half again as long in UTF-8, the room it makes. *)
  let size c = Uchar.utf_8_byte_length (Uchar.of_int c) in
  List.iter
    (fun (c, f) ->
       if (c < 128 && (c < 65 || c > 90 || f <> c + 32)) || 2 * size f > 3 * size c then
         failwith (Printf.sprintf "U+%04X folds to U+%04X: text.Fold must change first" c f))
    pairs;
  (* A run: its first and last character, the distance between two of them (1 or 2, 0 while it has only one) and the
     distance each moves. *)
  let runs =
    List.fold_left
      (fun runs (c, f) ->
         match runs with
         | (first, last, step, delta) :: rest when f - c = delta && (step = 0 || c = last + step) && c - last <= 2 ->
           (first, c, c - last, delta) :: rest
         | _ -> (c, c, 0, f - c) :: runs)
      [] pairs
  in
  print_string
    (Printf.sprintf
       "(* Generated by src/gen/gen_fold.ml from CaseFolding-%s.txt of the Unicode Character Database, statuses C and S:\n\
       \   %d characters in %d runs. Don't edit it: run the generator again. *)\n\n\
        let runs =\n\
       \  [|"
       version (List.length pairs) (List.length runs));
  List.iteri
    (fun k (first, last, step, delta) ->
       Printf.printf "%s0x%04X; 0x%04X; %d; %d;\n" (if k = 0 then " " else "     ") first last (max step 1) delta)
    (List.rev runs);
  print_string "  |]\n"

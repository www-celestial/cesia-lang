/* A call that lasts ms milliseconds without using the processor: what a slow call waits for, a disk or a network. */
EXPORT int64_t nap(int64_t ms) {
#ifdef _WIN32
  Sleep((DWORD) ms);
#else
  struct timespec left = { ms / 1000, (ms % 1000) * 1000000 };
  while (nanosleep(&left, &left) != 0) {}
#endif
  return ms;
}

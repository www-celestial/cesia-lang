EXPORT void sort_ints(int32_t *items, int n, int (*f)(int32_t, int32_t)) {
  for (int i = 1; i < n; i++)
    for (int j = i; j > 0 && compare_with(&items[j - 1], &items[j], f) > 0; j--) {

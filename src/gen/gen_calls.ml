(* Generates the C functions that call a C function by the shape of its signature: each argument is an integer or a
   float, and so is the result. "calls" prints src/sys/calls.c, "fixture" a library for the tests. *)
let max_args = 6
let is_float mask k = mask land (1 lsl k) <> 0
let index n mask = (1 lsl n) - 1 + mask
let id n mask float_result = (index n mask * 2) + if float_result then 1 else 0
let c_type float = if float then "double" else "int64_t"

let each_shape f =
  for n = 0 to max_args do
    for mask = 0 to (1 lsl n) - 1 do
      List.iter (f n mask) [ false; true ]
    done
  done

let params n mask = if n = 0 then "void" else String.concat ", " (List.init n (fun k -> c_type (is_float mask k)))

let print_call n mask float_result =
  Printf.printf "static void call_%d(void *f, int64_t *s) {\n" (id n mask float_result);
  for k = 0 to n - 1 do
    if is_float mask k then Printf.printf "  double d%d; memcpy(&d%d, &s[%d], 8);\n" k k k
  done;
  let args = String.concat ", " (List.init n (fun k -> Printf.sprintf (if is_float mask k then "d%d" else "s[%d]") k)) in
  let target = Printf.sprintf "((%s (*)(%s)) f)(%s)" (c_type float_result) (params n mask) args in
  if float_result then Printf.printf "  double r = %s;\n  memcpy(&s[6], &r, 8);\n}\n\n" target
  else Printf.printf "  s[6] = %s;\n}\n\n" target

let print_calls () =
  print_string
    "/* Generated by src/gen/gen_calls.ml. */\n#include <stdint.h>\n#include <stdlib.h>\n#include <string.h>\n\
     #include <caml/mlvalues.h>\n#include <caml/memory.h>\n#include <caml/fail.h>\n#include <caml/signals.h>\n\n";
  each_shape print_call;
  let ids = ref [] in
  each_shape (fun n mask float_result -> ids := id n mask float_result :: !ids);
  let table = List.map (Printf.sprintf "call_%d") (List.sort compare !ids) in
  Printf.printf "static void (*const calls[])(void *, int64_t *) = {\n  %s\n};\n\n" (String.concat ",\n  " table);
  print_string
    "value cesia_call(value fn, value id, value slots, value texts, value mask) {\n\
    \  int64_t *s = (int64_t *) Bytes_val(slots);\n\
    \  for (int k = 0; k < 6; k++)\n\
    \    if (Long_val(mask) >> k & 1) s[k] = (int64_t) String_val(Field(texts, k));\n\
    \  calls[Long_val(id)]((void *) Long_val(fn), s);\n\
    \  return Val_unit;\n\
     }\n\n";
  (* A slow call, on a domain of its own: its texts are copied first, since a collection may move them while it runs,
     and it runs with the runtime released, so that no collection waits for it. *)
  print_string
    "value cesia_call_released(value fn, value id, value slots, value texts, value mask) {\n\
    \  CAMLparam5(fn, id, slots, texts, mask);\n\
    \  int64_t s[7];\n\
    \  char *copies[6] = { 0 };\n\
    \  memcpy(s, Bytes_val(slots), sizeof s);\n\
    \  for (int k = 0; k < 6; k++)\n\
    \    if (Long_val(mask) >> k & 1) {\n\
    \      size_t n = caml_string_length(Field(texts, k));\n\
    \      copies[k] = malloc(n + 1);\n\
    \      if (copies[k] == NULL) {\n\
    \        for (int j = 0; j < k; j++) free(copies[j]);\n\
    \        caml_raise_out_of_memory();\n\
    \      }\n\
    \      memcpy(copies[k], String_val(Field(texts, k)), n);\n\
    \      copies[k][n] = 0;\n\
    \      s[k] = (int64_t) copies[k];\n\
    \    }\n\
    \  void *f = (void *) Long_val(fn);\n\
    \  long shape = Long_val(id);\n\
    \  caml_enter_blocking_section();\n\
    \  calls[shape](f, s);\n\
    \  caml_leave_blocking_section();\n\
    \  for (int k = 0; k < 6; k++) free(copies[k]);\n\
    \  memcpy(Bytes_val(slots), s, sizeof s);\n\
    \  CAMLreturn(Val_unit);\n\
     }\n"

(* One function per shape, whose result depends on every argument and its position. *)
let print_shape n mask float_result =
  let param k = Printf.sprintf "%s a%d" (c_type (is_float mask k)) k in
  let signature = if n = 0 then "void" else String.concat ", " (List.init n param) in
  let terms = List.init n (fun k -> Printf.sprintf " + %d.0 * a%d" (k + 1) k) in
  let sum = "0.0" ^ String.concat "" terms in
  if float_result then Printf.printf "EXPORT double shape_d_%d_%d(%s) { return %s; }\n" n mask signature sum
  else Printf.printf "EXPORT int64_t shape_i_%d_%d(%s) { return (int64_t) (2.0 * (%s)); }\n" n mask signature sum


(* Generates src/embedded.ml: the files of std/, embedded in the binary. *)

let () =
  print_string "(* Generated by gen/gen_embed.ml. Do not edit by hand. *)\nlet files = [\n";
  for i = 1 to Array.length Sys.argv - 1 do
    let path = Sys.argv.(i) in
    let name = Filename.remove_extension (Filename.basename path) in
    let src = In_channel.with_open_bin path In_channel.input_all in
    Printf.printf "  (%S, %S);\n" name src
  done;
  print_string "]\n"

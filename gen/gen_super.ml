(* Generates src/super.ml: the depth-2 superinstructions on + - *, for integers and floats. Forms: (a o1 b) o2 c and c
   o2 (a o1 b), where a and b are a variable or a constant, and c a variable, a constant or an expression. The integer
   version carries the overflow checks. *)

let ops = [ "Add", "+"; "Sub", "-"; "Mul", "*" ]
let pr = Printf.printf

(* The pairs (a, b): variable-variable, variable-constant, constant-variable. *)
let pairs = [ "L", "L"; "L", "K"; "K", "L" ]
let leaves = [ "L"; "K"; "X" ]

let header () =
  pr "(* Generated by gen/gen_super.ml. Do not edit by hand. *)\n";
  pr "open Types\n\n";
  pr "type op = Add | Sub | Mul\n";
  pr "type fl = FL of int | FK of float | FX of (ctx -> float)\n";
  pr "type il = IL of int | IK of int | IX of (ctx -> int)\n\n";
  pr "let[@inline] add_i ctx s x y =\n  let r = x + y in\n  if (x lxor r) land (y lxor r) < 0 then begin\n    ctx.site <- s;\n    Arith.add_int ctx x y\n  end else r\n\n";
  pr "let[@inline] sub_i ctx s x y =\n  let r = x - y in\n  if (x lxor y) land (x lxor r) < 0 then begin\n    ctx.site <- s;\n    Arith.sub_int ctx x y\n  end else r\n\n";
  pr "(* Both operands fit in 31 bits: the product can't overflow. *)\n";
  pr "let[@inline] mul_i ctx s x y =\n  if ((x + 0x40000000) lor (y + 0x40000000)) lsr 31 = 0 then x * y\n  else begin\n    ctx.site <- s;\n    Arith.mul_int ctx x y\n  end\n\n"

let fpat prefix v = function
  | "L" -> Printf.sprintf "%sL %s" prefix v
  | "K" -> Printf.sprintf "%sK %s" prefix v
  | _ -> Printf.sprintf "%sX %s" prefix v

let flo () =
  let read v = function
    | "L" -> Printf.sprintf "Float.Array.get f (b + %s)" v
    | _ -> v
  in
  let op s = s ^ "." in
  pr "let float_left o1 o2 a b c =\n  match o1, o2, a, b, c with\n";
  List.iter (fun (n1, s1) ->
      List.iter (fun (n2, s2) ->
          List.iter (fun (ka, kb) ->
              List.iter (fun kc ->
                  pr "  | %s, %s, %s, %s, %s ->\n" n1 n2 (fpat "F" "p" ka) (fpat "F" "q" kb) (fpat "F" "r" kc);
                  if kc = "X" then
                    pr "    Some (fun ctx -> let z = r ctx in let f = ctx.f and b = ctx.b in (%s %s %s) %s z)\n"
                      (read "p" ka) (op s1) (read "q" kb) (op s2)
                  else
                    pr "    Some (fun ctx -> let f = ctx.f and b = ctx.b in (%s %s %s) %s %s)\n"
                      (read "p" ka) (op s1) (read "q" kb) (op s2) (read "r" kc))
                leaves)
            pairs)
        ops)
    ops;
  pr "  | _ -> None\n\n";
  pr "let float_right o1 o2 c a b =\n  match o1, o2, c, a, b with\n";
  List.iter (fun (n1, s1) ->
      List.iter (fun (n2, s2) ->
          List.iter (fun (ka, kb) ->
              List.iter (fun kc ->
                  pr "  | %s, %s, %s, %s, %s ->\n" n1 n2 (fpat "F" "r" kc) (fpat "F" "p" ka) (fpat "F" "q" kb);
                  if kc = "X" then
                    pr "    Some (fun ctx -> let z = r ctx in let f = ctx.f and b = ctx.b in z %s (%s %s %s))\n"
                      (op s2) (read "p" ka) (op s1) (read "q" kb)
                  else
                    pr "    Some (fun ctx -> let f = ctx.f and b = ctx.b in %s %s (%s %s %s))\n"
                      (read "r" kc) (op s2) (read "p" ka) (op s1) (read "q" kb))
                leaves)
            pairs)
        ops)
    ops;
  pr "  | _ -> None\n\n"

let ints () =
  let read v = function
    | "L" -> Printf.sprintf "i.(b + %s)" v
    | _ -> v
  in
  let call n s x y =
    Printf.sprintf "%s_i ctx %s (%s) (%s)" (String.lowercase_ascii n) s x y
  in
  pr "let int_left s1 s2 o1 o2 a b c =\n  match o1, o2, a, b, c with\n";
  List.iter (fun (n1, _) ->
      List.iter (fun (n2, _) ->
          List.iter (fun (ka, kb) ->
              List.iter (fun kc ->
                  pr "  | %s, %s, %s, %s, %s ->\n" n1 n2 (fpat "I" "p" ka) (fpat "I" "q" kb) (fpat "I" "r" kc);
                  let inner = call n1 "s1" (read "p" ka) (read "q" kb) in
                  if kc = "X" then
                    pr "    Some (fun ctx -> let z = r ctx in let i = ctx.i and b = ctx.b in %s)\n"
                      (call n2 "s2" inner "z")
                  else
                    pr "    Some (fun ctx -> let i = ctx.i and b = ctx.b in %s)\n"
                      (call n2 "s2" inner (read "r" kc)))
                leaves)
            pairs)
        ops)
    ops;
  pr "  | _ -> None\n\n";
  pr "let int_right s1 s2 o1 o2 c a b =\n  match o1, o2, c, a, b with\n";
  List.iter (fun (n1, _) ->
      List.iter (fun (n2, _) ->
          List.iter (fun (ka, kb) ->
              List.iter (fun kc ->
                  pr "  | %s, %s, %s, %s, %s ->\n" n1 n2 (fpat "I" "r" kc) (fpat "I" "p" ka) (fpat "I" "q" kb);
                  let inner = call n1 "s1" (read "p" ka) (read "q" kb) in
                  if kc = "X" then
                    pr "    Some (fun ctx -> let z = r ctx in let i = ctx.i and b = ctx.b in %s)\n"
                      (call n2 "s2" "z" inner)
                  else
                    pr "    Some (fun ctx -> let i = ctx.i and b = ctx.b in %s)\n"
                      (call n2 "s2" (read "r" kc) inner))
                leaves)
            pairs)
        ops)
    ops;
  pr "  | _ -> None\n"

let () =
  header ();
  flo ();
  ints ()

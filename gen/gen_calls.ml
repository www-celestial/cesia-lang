#else
#define EXPORT
#endif
#define ECHO(name, type) EXPORT type echo_##name(type x) { return x; }
ECHO(i8, int8_t) ECHO(u8, uint8_t) ECHO(i16, int16_t) ECHO(u16, uint16_t) ECHO(i32, int32_t) ECHO(u32, uint32_t)
ECHO(i64, int64_t) ECHO(u64, uint64_t) ECHO(f32, float) ECHO(f64, double) ECHO(bool, bool) ECHO(ptr, void *)
EXPORT float float_mix(float a, double b, float c, int32_t d, double e, float f) { return a + b + c + d + e + f; }
EXPORT const char *text_constant(void) { return "from C"; }
EXPORT int64_t text_length(const char *text) { int64_t n = 0; while (text[n]) n++; return n; }
EXPORT const char *text_null(void) { return 0; }
EXPORT void *ptr_null(void) { return 0; }

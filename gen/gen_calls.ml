|}

let print_fixture () =
  print_string fixture;
  each_shape print_shape

(* A library that exists, and that no loader can finish loading. *)
let unloadable = "extern int kepler_nope(void);\nint calls_nope(void) { return kepler_nope(); }\n"

let () =
  match Sys.argv with
  | [| _; "calls" |] -> print_calls ()
  | [| _; "fixture" |] -> print_fixture ()
  | [| _; "unloadable" |] -> print_string unloadable
  | _ -> prerr_endline "usage: gen_calls calls|fixture|unloadable"; exit 2
